//! Providers: the plug-in contract every System 1 model implements (docs/14-providers.md,
//! ADR-0015).
//!
//! A [`Decider`] reads one rendered message and many typed questions in one call and returns raw
//! logits. Only a [`Calibration`] fitted for that (release, question) turns logits into a
//! [`Decision`]; without one there is no decision. An [`Embedder`] returns vectors tagged with
//! their [`SpaceId`], and vectors from different spaces are never compared. Every call first checks
//! the provider's [`Manifest`] against the [`DataClass`] of its input.

use std::collections::BTreeMap;

use crate::decision::{
    Decision, Distribution, DistributionError, ModelRelease, Question, QuestionId, QuestionKind,
};
use crate::tier::Tier;

/// Where a provider runs. Decides which data it may see.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Locality {
    /// Inside the daemon's process.
    InProcess,
    /// A service on our own hardware (llama.cpp, vLLM).
    LocalService,
    /// Anything outside our own hardware, such as an external API.
    Remote,
}

/// What kind of data an input contains.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DataClass {
    /// A public corpus whose terms allow sending it to the provider.
    Public,
    /// Generated by us.
    Synthetic,
    /// Mail of a customer or of any mailbox on the platform.
    Customer,
}

/// What a provider declares about itself. The registry is a data file of these.
#[derive(Debug, Clone, PartialEq)]
pub struct Manifest {
    /// Release id, recorded in every decision.
    pub release: ModelRelease,
    /// sha256 of the weights, if the provider has local weights.
    pub weights_sha256: Option<String>,
    /// Licence name, as published.
    pub licence: String,
    /// Whether the licence allows commercial use.
    pub commercial_use: bool,
    /// Where it runs.
    pub locality: Locality,
    /// Languages (BCP 47) the lab measured it on.
    pub measured_languages: Vec<String>,
    /// Longest input in tokens; the renderer truncates and records that it did.
    pub max_input_tokens: u32,
}

/// Why a provider call did not produce a result.
#[derive(Debug, Clone, PartialEq)]
pub enum ProviderError {
    /// The data rules forbid this provider from seeing this input.
    NotAllowed(&'static str),
    /// The provider cannot answer this question kind.
    Unsupported(QuestionId),
    /// No calibration was fitted for this release and question.
    Uncalibrated(QuestionId),
    /// The provider returned the wrong number of answers or outcomes.
    Shape(QuestionId),
    /// The distribution was invalid.
    Distribution(DistributionError),
    /// Two vectors from different spaces, or of different lengths.
    SpaceMismatch,
    /// The deadline passed.
    Timeout,
    /// The backend failed.
    Backend(String),
}

impl Manifest {
    /// The data rules of docs/14-providers.md section 4.
    pub fn may_process(&self, data: DataClass) -> Result<(), ProviderError> {
        match (data, self.locality) {
            (DataClass::Customer, Locality::Remote) => Err(ProviderError::NotAllowed(
                "customer mail never goes to a remote provider",
            )),
            (DataClass::Customer, _) if !self.commercial_use => Err(ProviderError::NotAllowed(
                "the licence does not allow commercial use",
            )),
            _ => Ok(()),
        }
    }
}

/// One message as a provider sees it: rendered text plus what the data rules need.
#[derive(Debug, Clone, Copy)]
pub struct Rendered<'a> {
    /// Text rendered for this provider (subject, sender, visible body, link and attachment summary).
    pub text: &'a str,
    /// Detected language (BCP 47), if confident.
    pub language: Option<&'a str>,
    /// What kind of data this is.
    pub data: DataClass,
}

/// A model that answers typed questions.
pub trait Decider: Send + Sync {
    /// What this provider is.
    fn manifest(&self) -> &Manifest;
    /// Whether it can answer this question.
    fn supports(&self, question: &Question) -> bool;
    /// Raw logits per question, in the question's outcome order, for all questions in one call.
    fn logits(
        &self,
        input: &Rendered<'_>,
        questions: &[Question],
    ) -> Result<Vec<Vec<f32>>, ProviderError>;
}

fn outcomes(q: &Question) -> usize {
    match &q.kind {
        QuestionKind::Noul => 2,
        QuestionKind::Choice { options } => options.len(),
        QuestionKind::Score { levels } => levels.len(),
    }
}

/// Question ids of user rules written in words start with this (`rule:<id>`).
pub const RULE_PREFIX: &str = "rule:";
/// The calibration entry that serves every user rule.
pub const RULE_CLASS: &str = "rule:*";

/// Temperatures fitted per question for one release, on the lab's dev split.
#[derive(Debug, Clone, PartialEq)]
pub struct Calibration {
    /// The release these temperatures belong to.
    pub release: ModelRelease,
    temperatures: BTreeMap<QuestionId, f32>,
}

impl Calibration {
    /// An empty calibration for a release.
    pub fn new(release: ModelRelease) -> Self {
        Self {
            release,
            temperatures: BTreeMap::new(),
        }
    }

    /// Record the fitted temperature for one question.
    pub fn set(&mut self, question: QuestionId, temperature: f32) {
        self.temperatures.insert(question, temperature);
    }

    /// The temperature for a question. A user rule (`rule:<id>`) has no calibration of its own:
    /// it takes the one fitted for rules as a class (`rule:*`, on the lab's rule set), if any.
    fn temperature(&self, question: &QuestionId) -> Option<f32> {
        self.temperatures.get(question).copied().or_else(|| {
            question
                .0
                .starts_with(RULE_PREFIX)
                .then(|| {
                    self.temperatures
                        .get(&QuestionId(RULE_CLASS.into()))
                        .copied()
                })
                .flatten()
        })
    }

    /// Whether this calibration can turn the question's logits into a decision.
    pub fn has(&self, question: &QuestionId) -> bool {
        self.temperature(question).is_some()
    }

    /// Turn raw logits into a calibrated distribution, or refuse without a fitted temperature.
    pub fn apply(
        &self,
        question: &Question,
        logits: &[f32],
    ) -> Result<Distribution, ProviderError> {
        if logits.len() != outcomes(question) {
            return Err(ProviderError::Shape(question.id.clone()));
        }
        let t = self
            .temperature(&question.id)
            .ok_or_else(|| ProviderError::Uncalibrated(question.id.clone()))?;
        Distribution::from_logits(logits, t).map_err(ProviderError::Distribution)
    }
}

/// Ask a decider all questions about one message and return calibrated decisions.
///
/// Checks, in order: the data rules, that every question is supported, that the calibration
/// belongs to this release, that one answer came back per question, and that every answer has
/// the question's shape and a fitted calibration. Any failure returns an error, never a guess.
pub fn decide(
    decider: &dyn Decider,
    calibration: &Calibration,
    tier: Tier,
    input: &Rendered<'_>,
    questions: &[Question],
) -> Result<Vec<Decision>, ProviderError> {
    let manifest = decider.manifest();
    manifest.may_process(input.data)?;
    if calibration.release != manifest.release {
        return Err(ProviderError::NotAllowed(
            "calibration fitted for another release",
        ));
    }
    if let Some(q) = questions.iter().find(|q| !decider.supports(q)) {
        return Err(ProviderError::Unsupported(q.id.clone()));
    }
    let raw = decider.logits(input, questions)?;
    if raw.len() != questions.len() {
        return Err(ProviderError::Shape(
            questions
                .first()
                .map_or_else(|| QuestionId(String::new()), |q| q.id.clone()),
        ));
    }
    questions
        .iter()
        .zip(raw)
        .map(|(q, logits)| {
            Ok(Decision {
                question: q.id.clone(),
                distribution: calibration.apply(q, &logits)?,
                tier,
                model: manifest.release.clone(),
            })
        })
        .collect()
}

/// A named embedding space: model release, version, preprocessing and dimension.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct SpaceId(pub String);

/// A vector that knows its space.
#[derive(Debug, Clone, PartialEq)]
pub struct Vector {
    /// The space it lives in.
    pub space: SpaceId,
    /// The values.
    pub values: Vec<f32>,
}

impl Vector {
    /// Cosine similarity, refused across spaces or lengths.
    pub fn cosine(&self, other: &Vector) -> Result<f32, ProviderError> {
        if self.space != other.space || self.values.len() != other.values.len() {
            return Err(ProviderError::SpaceMismatch);
        }
        let dot: f32 = self
            .values
            .iter()
            .zip(&other.values)
            .map(|(a, b)| a * b)
            .sum();
        let na: f32 = self.values.iter().map(|a| a * a).sum::<f32>().sqrt();
        let nb: f32 = other.values.iter().map(|b| b * b).sum::<f32>().sqrt();
        if na == 0.0 || nb == 0.0 {
            return Ok(0.0);
        }
        Ok(dot / (na * nb))
    }
}

/// A model that embeds text.
pub trait Embedder: Send + Sync {
    /// What this provider is.
    fn manifest(&self) -> &Manifest;
    /// The space its vectors live in.
    fn space(&self) -> &SpaceId;
    /// One vector per input, in order.
    fn embed_raw(&self, inputs: &[Rendered<'_>]) -> Result<Vec<Vec<f32>>, ProviderError>;
}

/// Embed inputs after checking the data rules for each of them, tagging every vector with its space.
pub fn embed(
    embedder: &dyn Embedder,
    inputs: &[Rendered<'_>],
) -> Result<Vec<Vector>, ProviderError> {
    for input in inputs {
        embedder.manifest().may_process(input.data)?;
    }
    let raw = embedder.embed_raw(inputs)?;
    if raw.len() != inputs.len() {
        return Err(ProviderError::SpaceMismatch);
    }
    Ok(raw
        .into_iter()
        .map(|values| Vector {
            space: embedder.space().clone(),
            values,
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest(locality: Locality, commercial_use: bool) -> Manifest {
        Manifest {
            release: ModelRelease("test-model@1".into()),
            weights_sha256: None,
            licence: "Apache-2.0".into(),
            commercial_use,
            locality,
            measured_languages: vec!["nl".into(), "en".into()],
            max_input_tokens: 512,
        }
    }

    fn noul(id: &str) -> Question {
        Question {
            id: QuestionId(id.into()),
            text: "Is this asking for a payment?".into(),
            kind: QuestionKind::Noul,
        }
    }

    struct Fixed {
        m: Manifest,
        out: Vec<Vec<f32>>,
    }

    impl Decider for Fixed {
        fn manifest(&self) -> &Manifest {
            &self.m
        }
        fn supports(&self, q: &Question) -> bool {
            matches!(q.kind, QuestionKind::Noul)
        }
        fn logits(&self, _: &Rendered<'_>, _: &[Question]) -> Result<Vec<Vec<f32>>, ProviderError> {
            Ok(self.out.clone())
        }
    }

    fn calibrated(ids: &[&str]) -> Calibration {
        let mut c = Calibration::new(ModelRelease("test-model@1".into()));
        for id in ids {
            c.set(QuestionId((*id).into()), 1.0);
        }
        c
    }

    const CUSTOMER: Rendered<'static> = Rendered {
        text: "Graag vandaag betalen naar het nieuwe rekeningnummer.",
        language: Some("nl"),
        data: DataClass::Customer,
    };

    #[test]
    fn customer_mail_never_goes_remote_or_to_non_commercial_licences() {
        assert!(
            manifest(Locality::Remote, true)
                .may_process(DataClass::Customer)
                .is_err()
        );
        assert!(
            manifest(Locality::InProcess, false)
                .may_process(DataClass::Customer)
                .is_err()
        );
        assert!(
            manifest(Locality::LocalService, true)
                .may_process(DataClass::Customer)
                .is_ok()
        );
        assert!(
            manifest(Locality::Remote, false)
                .may_process(DataClass::Public)
                .is_ok()
        );
    }

    #[test]
    fn many_questions_in_one_call_become_calibrated_decisions() {
        let d = Fixed {
            m: manifest(Locality::InProcess, true),
            out: vec![vec![0.0, 2.0], vec![1.0, 0.0]],
        };
        let qs = [noul("asks_payment"), noul("secrecy")];
        let out = decide(
            &d,
            &calibrated(&["asks_payment", "secrecy"]),
            Tier::SmallModels,
            &CUSTOMER,
            &qs,
        )
        .unwrap();
        assert_eq!(out.len(), 2);
        assert!(out[0].p_true().unwrap() > 0.5);
        assert!(out[1].p_true().unwrap() < 0.5);
        assert_eq!(out[0].model, ModelRelease("test-model@1".into()));
    }

    #[test]
    fn no_calibration_no_decision() {
        let d = Fixed {
            m: manifest(Locality::InProcess, true),
            out: vec![vec![0.0, 2.0]],
        };
        assert_eq!(
            decide(
                &d,
                &calibrated(&[]),
                Tier::SmallModels,
                &CUSTOMER,
                &[noul("asks_payment")]
            ),
            Err(ProviderError::Uncalibrated(QuestionId(
                "asks_payment".into()
            )))
        );
        let other = Calibration::new(ModelRelease("other@2".into()));
        assert!(matches!(
            decide(
                &d,
                &other,
                Tier::SmallModels,
                &CUSTOMER,
                &[noul("asks_payment")]
            ),
            Err(ProviderError::NotAllowed(_))
        ));
    }

    #[test]
    fn user_rules_share_the_class_calibration_and_nothing_else_does() {
        let q = noul("rule:refunds");
        assert!(!calibrated(&[]).has(&q.id));
        let c = calibrated(&[RULE_CLASS]);
        assert!(c.has(&q.id));
        assert!(c.apply(&q, &[0.0, 1.0]).is_ok());
        assert!(!c.has(&QuestionId("asks_payment".into())));
    }

    #[test]
    fn wrong_shapes_and_unsupported_questions_are_refused() {
        let d = Fixed {
            m: manifest(Locality::InProcess, true),
            out: vec![vec![0.0, 1.0, 2.0]],
        };
        assert!(matches!(
            decide(
                &d,
                &calibrated(&["q"]),
                Tier::SmallModels,
                &CUSTOMER,
                &[noul("q")]
            ),
            Err(ProviderError::Shape(_))
        ));
        let missing = Fixed {
            m: manifest(Locality::InProcess, true),
            out: vec![],
        };
        assert!(matches!(
            decide(
                &missing,
                &calibrated(&["q"]),
                Tier::SmallModels,
                &CUSTOMER,
                &[noul("q")]
            ),
            Err(ProviderError::Shape(_))
        ));
        let choice = Question {
            id: QuestionId("kind".into()),
            text: "Which kind?".into(),
            kind: QuestionKind::Choice {
                options: vec!["a".into(), "b".into()],
            },
        };
        assert_eq!(
            decide(
                &d,
                &calibrated(&["kind"]),
                Tier::SmallModels,
                &CUSTOMER,
                &[choice]
            ),
            Err(ProviderError::Unsupported(QuestionId("kind".into())))
        );
    }

    #[test]
    fn remote_decider_is_refused_before_it_is_called() {
        struct Panics(Manifest);
        impl Decider for Panics {
            fn manifest(&self) -> &Manifest {
                &self.0
            }
            fn supports(&self, _: &Question) -> bool {
                true
            }
            fn logits(
                &self,
                _: &Rendered<'_>,
                _: &[Question],
            ) -> Result<Vec<Vec<f32>>, ProviderError> {
                panic!("customer mail reached a remote provider")
            }
        }
        let d = Panics(manifest(Locality::Remote, true));
        assert!(matches!(
            decide(
                &d,
                &calibrated(&["q"]),
                Tier::DecisionModel,
                &CUSTOMER,
                &[noul("q")]
            ),
            Err(ProviderError::NotAllowed(_))
        ));
    }

    struct Constant {
        m: Manifest,
        space: SpaceId,
    }

    impl Embedder for Constant {
        fn manifest(&self) -> &Manifest {
            &self.m
        }
        fn space(&self) -> &SpaceId {
            &self.space
        }
        fn embed_raw(&self, inputs: &[Rendered<'_>]) -> Result<Vec<Vec<f32>>, ProviderError> {
            Ok(inputs.iter().map(|_| vec![1.0, 0.0, 0.0]).collect())
        }
    }

    #[test]
    fn vectors_from_different_spaces_never_meet() {
        let a = Constant {
            m: manifest(Locality::InProcess, true),
            space: SpaceId("e5-small@1/v1/384".into()),
        };
        let b = Constant {
            m: manifest(Locality::InProcess, true),
            space: SpaceId("harrier-270m@1/v1/640".into()),
        };
        let va = embed(&a, &[CUSTOMER]).unwrap();
        let vb = embed(&b, &[CUSTOMER]).unwrap();
        assert!((va[0].cosine(&va[0]).unwrap() - 1.0).abs() < 1e-6);
        assert_eq!(va[0].cosine(&vb[0]), Err(ProviderError::SpaceMismatch));
    }

    #[test]
    fn embedder_checks_data_rules_per_input() {
        let remote = Constant {
            m: manifest(Locality::Remote, true),
            space: SpaceId("remote@1".into()),
        };
        let public = Rendered {
            data: DataClass::Public,
            ..CUSTOMER
        };
        assert!(embed(&remote, &[public]).is_ok());
        assert!(embed(&remote, &[public, CUSTOMER]).is_err());
    }
}
